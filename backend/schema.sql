-- schema.sql
-- Sistem Persediaan untuk Perusahaan Konstruksi
--
-- Isi file ini:
--   1. Hapus objek lama (supaya file bisa dijalankan ulang dari nol)
--   2. Sequence untuk nomor bukti otomatis
--   3. 13 tabel beserta relasinya (foreign key)
--   4. View untuk laporan (buku besar, saldo akun, rekap pemakaian)
--   5. Row Level Security (RLS) dan hak akses untuk anon key
--
-- URUTAN MENJALANKAN: schema.sql -> triggers.sql -> seed.sql
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. HAPUS OBJEK LAMA
-- PERHATIAN: bagian ini MENGHAPUS SEMUA DATA. Berguna kalau kamu ingin
-- mengulang dari awal. "cascade" ikut menghapus trigger & view terkait.
-- ---------------------------------------------------------------------
drop view if exists v_buku_besar, v_saldo_akun, v_rekap_pemakaian_proyek,
  v_cek_keseimbangan_jurnal cascade;

drop table if exists
  jurnal_detail, jurnal, kartu_stok, stok_opname,
  pemakaian_detail, pemakaian, pembayaran_utang,
  pembelian_detail, pembelian, proyek, supplier, material, akun
cascade;

drop sequence if exists seq_no_pemakaian, seq_no_pembayaran, seq_no_opname;


-- ---------------------------------------------------------------------
-- 2. SEQUENCE NOMOR BUKTI
-- Sequence = penghitung otomatis 1, 2, 3, ... yang tidak pernah kembar.
-- Dipakai untuk membuat nomor bukti seperti PK-20261010-0001.
-- ---------------------------------------------------------------------
create sequence seq_no_pemakaian;   -- PK  = Pemakaian material
create sequence seq_no_pembayaran;  -- BKK = Bukti Kas Keluar (bayar utang)
create sequence seq_no_opname;      -- SO  = Stok Opname


-- ---------------------------------------------------------------------
-- 3. TABEL
-- "generated by default as identity" = id terisi otomatis (1, 2, 3, ...)
-- numeric(18,2) = angka desimal, cocok untuk uang (jangan pakai float!)
-- ---------------------------------------------------------------------

-- 3.1 Daftar akun (Chart of Accounts)
create table akun (
  id            bigint generated by default as identity primary key,
  kode          varchar(10)  not null unique,
  nama          varchar(100) not null,
  jenis         varchar(20)  not null
                check (jenis in ('Aset', 'Liabilitas', 'Ekuitas', 'Pendapatan', 'Beban')),
  saldo_normal  char(1)      not null check (saldo_normal in ('D', 'K'))  -- D = Debit, K = Kredit
);

-- 3.2 Material (barang persediaan)
-- Kolom stok, harga_rata_rata, dan nilai_stok HANYA diubah oleh trigger,
-- tidak boleh diisi manual dari aplikasi (lihat bagian hak akses di bawah).
--
-- Kenapa ada kolom nilai_stok (tambahan di luar spesifikasi)?
--   Kalau nilai persediaan dihitung stok x harga_rata_rata, pembulatan
--   desimal bisa membuat selisih beberapa rupiah dengan Buku Besar.
--   Dengan menyimpan nilai_stok (total rupiah) secara langsung, total di
--   Laporan Persediaan SELALU sama persis dengan saldo akun Persediaan.
create table material (
  id               bigint generated by default as identity primary key,
  kode             varchar(20)   not null unique,
  nama             varchar(100)  not null,
  kategori         varchar(50)   not null,
  satuan           varchar(20)   not null,
  stok             numeric(14,2) not null default 0 check (stok >= 0),
  harga_rata_rata  numeric(18,4) not null default 0 check (harga_rata_rata >= 0),
  nilai_stok       numeric(18,2) not null default 0 check (nilai_stok >= 0),
  stok_minimum     numeric(14,2) not null default 0 check (stok_minimum >= 0),
  created_at       timestamptz   not null default now()
);

-- 3.3 Supplier
create table supplier (
  id          bigint generated by default as identity primary key,
  nama        varchar(100) not null,
  alamat      text,
  telepon     varchar(30),
  created_at  timestamptz  not null default now()
);

-- 3.4 Proyek
create table proyek (
  id             bigint generated by default as identity primary key,
  nama           varchar(150) not null,
  lokasi         varchar(150),
  tanggal_mulai  date         not null,
  status         varchar(10)  not null default 'berjalan'
                 check (status in ('berjalan', 'selesai')),
  created_at     timestamptz  not null default now()
);

-- 3.5 Pembelian (header / kepala faktur)
create table pembelian (
  id           bigint generated by default as identity primary key,
  supplier_id  bigint        not null references supplier (id),
  tanggal      date          not null,
  no_faktur    varchar(50)   not null,
  cara_bayar   varchar(10)   not null check (cara_bayar in ('tunai', 'kredit')),
  total        numeric(18,2) not null default 0 check (total >= 0),
  sisa_utang   numeric(18,2) not null default 0,
  keterangan   text,
  created_at   timestamptz   not null default now(),
  -- satu supplier tidak boleh punya nomor faktur kembar
  unique (supplier_id, no_faktur),
  -- sisa utang tidak boleh minus dan tidak boleh melebihi total
  check (sisa_utang >= 0 and sisa_utang <= total)
);

-- 3.6 Pembelian detail (baris-baris material dalam satu faktur)
create table pembelian_detail (
  id            bigint generated by default as identity primary key,
  pembelian_id  bigint        not null references pembelian (id),
  material_id   bigint        not null references material (id),
  jumlah        numeric(14,2) not null check (jumlah > 0),
  harga_satuan  numeric(18,2) not null check (harga_satuan > 0),
  subtotal      numeric(18,2) not null   -- dihitung oleh trigger
);

-- 3.7 Pembayaran utang (cicilan / pelunasan pembelian kredit)
create table pembayaran_utang (
  id            bigint generated by default as identity primary key,
  pembelian_id  bigint        not null references pembelian (id),
  tanggal       date          not null,
  no_bukti      varchar(50)   not null unique,
  jumlah_bayar  numeric(18,2) not null check (jumlah_bayar > 0),
  keterangan    text,
  created_at    timestamptz   not null default now()
);

-- 3.8 Pemakaian material ke proyek (header)
create table pemakaian (
  id          bigint generated by default as identity primary key,
  proyek_id   bigint        not null references proyek (id),
  tanggal     date          not null,
  no_bukti    varchar(50)   not null unique,
  keterangan  text,
  total       numeric(18,2) not null default 0,  -- total nilai (harga pokok) semua baris
  created_at  timestamptz   not null default now()
);

-- 3.9 Pemakaian detail
create table pemakaian_detail (
  id            bigint generated by default as identity primary key,
  pemakaian_id  bigint        not null references pemakaian (id),
  material_id   bigint        not null references material (id),
  jumlah        numeric(14,2) not null check (jumlah > 0),
  harga_pokok   numeric(18,4) not null,  -- = harga rata-rata saat pemakaian (diisi trigger)
  subtotal      numeric(18,2) not null   -- = jumlah x harga pokok (diisi trigger)
);

-- 3.10 Stok opname (hasil hitung fisik gudang)
create table stok_opname (
  id             bigint generated by default as identity primary key,
  material_id    bigint        not null references material (id),
  tanggal        date          not null,
  no_bukti       varchar(50)   not null unique,
  stok_sistem    numeric(14,2) not null,  -- diisi trigger: stok di sistem sebelum opname
  stok_fisik     numeric(14,2) not null check (stok_fisik >= 0),
  selisih        numeric(14,2) not null,  -- fisik - sistem (minus = barang kurang)
  nilai_selisih  numeric(18,2) not null,  -- selisih x harga rata-rata
  keterangan     text,
  created_at     timestamptz   not null default now()
);

-- 3.11 Kartu stok (riwayat mutasi tiap material) — diisi otomatis trigger
create table kartu_stok (
  id               bigint generated by default as identity primary key,
  material_id      bigint        not null references material (id),
  tanggal          date          not null,
  jenis_transaksi  varchar(20)   not null
                   check (jenis_transaksi in ('PEMBELIAN', 'PEMAKAIAN', 'STOK_OPNAME')),
  no_bukti         varchar(50)   not null,
  keterangan       text,
  masuk            numeric(14,2) not null default 0,
  keluar           numeric(14,2) not null default 0,
  harga            numeric(18,4) not null default 0,  -- harga per satuan mutasi ini
  nilai_masuk      numeric(18,2) not null default 0,
  nilai_keluar     numeric(18,2) not null default 0,
  saldo_jumlah     numeric(14,2) not null,            -- stok setelah mutasi
  saldo_nilai      numeric(18,2) not null,            -- nilai stok setelah mutasi
  created_at       timestamptz   not null default now()
);

-- 3.12 Jurnal (header)
create table jurnal (
  id          bigint generated by default as identity primary key,
  tanggal     date         not null,
  no_bukti    varchar(50)  not null,
  keterangan  text,
  sumber      varchar(20)  not null
              check (sumber in ('SALDO_AWAL', 'PEMBELIAN', 'PEMBAYARAN_UTANG',
                                'PEMAKAIAN', 'STOK_OPNAME')),
  sumber_id   bigint,       -- id transaksi asal (mis. id pembelian)
  created_at  timestamptz  not null default now()
);

-- 3.13 Jurnal detail (baris debit/kredit — double entry)
create table jurnal_detail (
  id         bigint generated by default as identity primary key,
  jurnal_id  bigint        not null references jurnal (id),
  akun_id    bigint        not null references akun (id),
  debit      numeric(18,2) not null default 0,
  kredit     numeric(18,2) not null default 0,
  -- tiap baris hanya boleh berisi debit ATAU kredit, dan tidak boleh nol
  check (debit >= 0 and kredit >= 0),
  check (debit = 0 or kredit = 0),
  check (debit + kredit > 0)
);

-- Index = "daftar isi" agar pencarian/filter lebih cepat
create index idx_pembelian_detail_pembelian on pembelian_detail (pembelian_id);
create index idx_pemakaian_detail_pemakaian on pemakaian_detail (pemakaian_id);
create index idx_pembayaran_pembelian       on pembayaran_utang (pembelian_id);
create index idx_kartu_stok_material        on kartu_stok (material_id, tanggal, id);
create index idx_jurnal_tanggal             on jurnal (tanggal, id);
create index idx_jurnal_detail_jurnal       on jurnal_detail (jurnal_id);
create index idx_jurnal_detail_akun         on jurnal_detail (akun_id);


-- ---------------------------------------------------------------------
-- 4. VIEW (tabel "virtual" hasil query, memudahkan frontend)
-- security_invoker = true artinya view mengikuti hak akses & RLS milik
-- pengguna yang membaca (aman, dan tidak memicu peringatan Supabase).
-- ---------------------------------------------------------------------

-- 4.1 Buku besar: semua baris jurnal lengkap dengan tanggal & nama akun
create view v_buku_besar with (security_invoker = true) as
select
  jd.id,
  j.id          as jurnal_id,
  j.tanggal,
  j.no_bukti,
  j.keterangan,
  j.sumber,
  a.id          as akun_id,
  a.kode        as kode_akun,
  a.nama        as nama_akun,
  a.saldo_normal,
  jd.debit,
  jd.kredit
from jurnal_detail jd
join jurnal j on j.id = jd.jurnal_id
join akun   a on a.id = jd.akun_id;

-- 4.2 Saldo tiap akun (sesuai saldo normalnya)
create view v_saldo_akun with (security_invoker = true) as
select
  a.id,
  a.kode,
  a.nama,
  a.jenis,
  a.saldo_normal,
  coalesce(sum(jd.debit), 0)  as total_debit,
  coalesce(sum(jd.kredit), 0) as total_kredit,
  case
    when a.saldo_normal = 'D' then coalesce(sum(jd.debit), 0) - coalesce(sum(jd.kredit), 0)
    else coalesce(sum(jd.kredit), 0) - coalesce(sum(jd.debit), 0)
  end as saldo
from akun a
left join jurnal_detail jd on jd.akun_id = a.id
group by a.id;

-- 4.3 Rekap pemakaian material per proyek
create view v_rekap_pemakaian_proyek with (security_invoker = true) as
select
  p.id          as proyek_id,
  p.nama        as nama_proyek,
  p.status,
  m.id          as material_id,
  m.kode        as kode_material,
  m.nama        as nama_material,
  m.satuan,
  sum(d.jumlah)   as total_jumlah,
  sum(d.subtotal) as total_nilai
from pemakaian_detail d
join pemakaian h on h.id = d.pemakaian_id
join proyek    p on p.id = h.proyek_id
join material  m on m.id = d.material_id
group by p.id, m.id;

-- 4.4 Alat bantu cek: total debit & kredit tiap jurnal (harus selalu sama)
create view v_cek_keseimbangan_jurnal with (security_invoker = true) as
select
  j.id, j.tanggal, j.no_bukti, j.sumber,
  sum(jd.debit)  as total_debit,
  sum(jd.kredit) as total_kredit,
  sum(jd.debit) = sum(jd.kredit) as seimbang
from jurnal j
join jurnal_detail jd on jd.jurnal_id = j.id
group by j.id;


-- ---------------------------------------------------------------------
-- 5. ROW LEVEL SECURITY (RLS) & HAK AKSES
--
-- Di Supabase, frontend memakai "anon key" (kunci publik). Siapa pun yang
-- membuka web kita bisa melihat kunci ini, jadi database HARUS membatasi
-- apa yang boleh dilakukan pemilik anon key. Caranya dua lapis:
--
--   a) GRANT/REVOKE  -> boleh tidaknya role "anon" menyentuh tabel/kolom.
--   b) RLS + POLICY  -> baris mana yang boleh dibaca/ditulis.
--
-- Aturan yang kita pakai:
--   * Semua tabel boleh DIBACA (select).
--   * Supplier, proyek, material boleh DITAMBAH & DIUBAH (data master),
--     tapi kolom stok/harga/nilai material TIDAK boleh diubah langsung.
--   * Tabel transaksi (pembelian, pemakaian, jurnal, dst.) TIDAK boleh
--     ditulis langsung. Satu-satunya jalan adalah memanggil fungsi RPC
--     simpan_... (dibuat di triggers.sql) yang berjalan sebagai pemilik
--     database ("security definer").
--   * Tidak ada policy UPDATE/DELETE untuk transaksi -> transaksi yang
--     sudah tersimpan tidak bisa diedit/dihapus dari aplikasi.
--
-- Role "authenticated" ikut diberi hak yang sama, berjaga-jaga kalau
-- nanti kamu menambahkan fitur login (Supabase Auth).
-- ---------------------------------------------------------------------

-- 5.1 Aktifkan RLS di semua tabel. Tanpa policy, RLS = semua ditolak.
alter table akun             enable row level security;
alter table material         enable row level security;
alter table supplier         enable row level security;
alter table proyek           enable row level security;
alter table pembelian        enable row level security;
alter table pembelian_detail enable row level security;
alter table pembayaran_utang enable row level security;
alter table pemakaian        enable row level security;
alter table pemakaian_detail enable row level security;
alter table stok_opname      enable row level security;
alter table kartu_stok       enable row level security;
alter table jurnal           enable row level security;
alter table jurnal_detail    enable row level security;

-- 5.2 Policy BACA untuk semua tabel
create policy "boleh baca" on akun             for select to anon, authenticated using (true);
create policy "boleh baca" on material         for select to anon, authenticated using (true);
create policy "boleh baca" on supplier         for select to anon, authenticated using (true);
create policy "boleh baca" on proyek           for select to anon, authenticated using (true);
create policy "boleh baca" on pembelian        for select to anon, authenticated using (true);
create policy "boleh baca" on pembelian_detail for select to anon, authenticated using (true);
create policy "boleh baca" on pembayaran_utang for select to anon, authenticated using (true);
create policy "boleh baca" on pemakaian        for select to anon, authenticated using (true);
create policy "boleh baca" on pemakaian_detail for select to anon, authenticated using (true);
create policy "boleh baca" on stok_opname      for select to anon, authenticated using (true);
create policy "boleh baca" on kartu_stok       for select to anon, authenticated using (true);
create policy "boleh baca" on jurnal           for select to anon, authenticated using (true);
create policy "boleh baca" on jurnal_detail    for select to anon, authenticated using (true);

-- 5.3 Policy TAMBAH & UBAH untuk data master saja
create policy "boleh tambah" on supplier for insert to anon, authenticated with check (true);
create policy "boleh ubah"   on supplier for update to anon, authenticated using (true) with check (true);
create policy "boleh tambah" on proyek   for insert to anon, authenticated with check (true);
create policy "boleh ubah"   on proyek   for update to anon, authenticated using (true) with check (true);
create policy "boleh tambah" on material for insert to anon, authenticated with check (true);
create policy "boleh ubah"   on material for update to anon, authenticated using (true) with check (true);

-- 5.4 Hak akses tabel (GRANT). Mulai dari nol, lalu buka seperlunya.
revoke all on all tables    in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

grant select on all tables in schema public to anon, authenticated;  -- termasuk view
grant insert, update on supplier, proyek to anon, authenticated;

-- Material: hanya kolom data master yang boleh diisi/diubah.
-- stok, harga_rata_rata, nilai_stok sengaja TIDAK disebut -> ditolak.
grant insert (kode, nama, kategori, satuan, stok_minimum) on material to anon, authenticated;
grant update (kode, nama, kategori, satuan, stok_minimum) on material to anon, authenticated;
